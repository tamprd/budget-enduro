def write(page, title, desc, body, cta=True, sticky=True):
    html = head(title, desc, page) + header(page) + body
    if cta:
        html += CTA_BAND
    footer = FOOTER
    if not sticky:
        footer = re.sub(r'<div class="sticky-cta">.*?</div>\n\n', '', footer, flags=re.S)
    html += footer
    with open(os.path.join(OUT, page), 'w', encoding='utf-8') as f:
        f.write(html)
    print(f'  {page:22s} {len(html):>7,} bytes')


