def min_lap_text(v):
    return '%d sec' % v['min_lap'] if v['min_lap'] else 'To be advised'


def emit_venues_js():
    """One source of truth -> a runtime module the pages read."""
    import json
    rows = ',\n'.join('  ' + json.dumps(v) for v in VENUES)
    js = ('/* GENERATED BY build.py - do not edit by hand. */\n'
          'var VENUES = [\n' + rows + '\n];\n'
          'var VENUE = {};\n'
          'VENUES.forEach(function(v){ VENUE[v.slug] = v; });\n')
    path = os.path.join(OUT, 'assets', 'venues.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(js)
    print('  assets/venues.js       %7s bytes' % format(len(js), ','))


